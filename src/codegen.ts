// Go programs that do what the page shows, with the same settings. The output
// is gofmt-clean, and test/codegen.test.ts runs it against every release.

import { DEFAULT_OPTIONS, algo, isEncoder, type AlgoId, type EncoderId, type MetricId, type Options } from './types';

const str = (s: string) => JSON.stringify(s);

function levExpr(o: Options): string {
  return o.insertCost === 1 && o.deleteCost === 1 && o.replaceCost === 1
    ? 'strsim.NewLevenshtein()'
    : `&strsim.LevenshteinMetric{InsertCost: ${o.insertCost}, DeleteCost: ${o.deleteCost}, ReplaceCost: ${o.replaceCost}}`;
}

function jwExpr(o: Options): string {
  return o.boostThreshold === DEFAULT_OPTIONS.boostThreshold && o.prefixSize === DEFAULT_OPTIONS.prefixSize
    ? 'strsim.NewJaroWinkler()'
    : `&strsim.JaroWinklerMetric{BoostThreshold: ${o.boostThreshold}, PrefixSize: ${o.prefixSize}}`;
}

const ngramExpr = (o: Options) => (o.ngramSize === 2 ? 'strsim.NewNgram()' : `&strsim.NgramMetric{Size: ${o.ngramSize}}`);

const ENCODER_GO: Record<EncoderId, { ctor: string; type: string; field: keyof Options; def: number }> = {
  soundex: { ctor: 'NewSoundex', type: 'SoundexEncoder', field: 'soundexLength', def: 4 },
  metaphone: { ctor: 'NewMetaphone', type: 'MetaphoneEncoder', field: 'metaphoneLength', def: 4 },
  doublemetaphone: { ctor: 'NewDoubleMetaphone', type: 'DoubleMetaphoneEncoder', field: 'doubleMetaphoneLength', def: 4 },
  nysiis: { ctor: 'NewNYSIIS', type: 'NYSIISEncoder', field: 'nysiisLength', def: 6 },
};

function encoderExpr(id: EncoderId, o: Options): string {
  const g = ENCODER_GO[id];
  const n = o[g.field] as number;
  return n === g.def ? `strsim.${g.ctor}()` : `&strsim.${g.type}{MaxLength: ${n}}`;
}

/** cosine, jaccard and overlap are NgramMetric methods, not a strsim.Metric: an adapter makes them one. */
const ADAPTED = new Set<MetricId>(['cosine', 'jaccard', 'overlap']);
const goName = (id: MetricId) => id[0].toUpperCase() + id.slice(1);

function adapter(id: MetricId): string[] {
  if (!ADAPTED.has(id)) return [];
  return [
    `// ${id} turns NgramMetric.${goName(id)} into a strsim.Metric (NgramMetric.Similarity is Dice).`,
    `type ${id} struct{ *strsim.NgramMetric }`,
    '',
    `func (m ${id}) Similarity(a, b string) float64 { return m.${goName(id)}(a, b) }`,
    '',
  ];
}

/** An expression of type strsim.Metric. */
function metricExpr(id: MetricId, o: Options): string {
  switch (id) {
    case 'levenshtein':
      return levExpr(o);
    case 'osa':
      return 'strsim.NewOSA()';
    case 'damerau':
      return 'strsim.NewDamerauLevenshtein()';
    case 'lcs':
      return 'strsim.NewLCS()';
    case 'hamming':
      return 'strsim.NewHamming()';
    case 'jaro':
      return 'strsim.NewJaro()';
    case 'jarowinkler':
      return jwExpr(o);
    case 'dice':
      return ngramExpr(o);
    default:
      return `${id}{${ngramExpr(o)}}`;
  }
}

function file(version: string, imports: string[], body: string[]): string {
  const std = imports.filter((i) => !i.includes('.')).sort();
  const lines = [
    `// Generated by the strsim playground for strsim ${version}.`,
    `// Add it to your module with: go get github.com/jcoruiz/strsim@${version}`,
    'package main',
    '',
    'import (',
    ...std.map((i) => `\t${str(i)}`),
    ...(std.length ? [''] : []),
    '\t"github.com/jcoruiz/strsim"',
    ')',
    '',
    ...body,
  ];
  return lines.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd() + '\n';
}

export function compareProgram(a: string, b: string, o: Options, version: string): string {
  const lower = o.ignoreCase ? ['\t// Compared ignoring case, as in the playground.', '\ta, b = strings.ToLower(a), strings.ToLower(b)', ''] : [];
  const row = (name: string, expr: string) => `\tfmt.Printf("%-20s %.4f\\n", ${str(name)}, ${expr})`;
  const rowD = (name: string, sim: string, dist: string) => `\tfmt.Printf("%-20s %.4f  distance %d\\n", ${str(name)}, ${sim}, ${dist})`;
  const code = (name: string, v: string) => `\tfmt.Printf("%-20s %-10q %-10q %t\\n", ${str(name)}, ${v}.Encode(a), ${v}.Encode(b), ${v}.Match(a, b))`;
  const body = [
    'func main() {',
    `\ta, b := ${str(a)}, ${str(b)}`,
    '',
    ...lower,
    `\tlev := ${levExpr(o)}`,
    `\tjw := ${jwExpr(o)}`,
    `\tngram := ${ngramExpr(o)}`,
    '',
    rowD('Levenshtein', 'lev.Similarity(a, b)', 'lev.Distance(a, b)'),
    rowD('OSA', 'strsim.OSASimilarity(a, b)', 'strsim.OSA(a, b)'),
    rowD('Damerau-Levenshtein', 'strsim.DamerauLevenshteinSimilarity(a, b)', 'strsim.DamerauLevenshtein(a, b)'),
    rowD('LCS', 'strsim.LCSSimilarity(a, b)', 'strsim.LCSDistance(a, b)'),
    '\tif d, err := strsim.Hamming(a, b); err == nil {',
    `\t${rowD('Hamming', 'strsim.HammingSimilarity(a, b)', 'd')}`,
    '\t} else {',
    `\t\tfmt.Printf("%-20s %.4f  %v\\n", "Hamming", strsim.HammingSimilarity(a, b), err)`,
    '\t}',
    row('Jaro', 'strsim.JaroSimilarity(a, b)'),
    row('Jaro-Winkler', 'jw.Similarity(a, b)'),
    row('Cosine', 'ngram.Cosine(a, b)'),
    row('Jaccard', 'ngram.Jaccard(a, b)'),
    row('Sørensen-Dice', 'ngram.Dice(a, b)'),
    row('Overlap', 'ngram.Overlap(a, b)'),
    '',
    '\t// Codes of a and b (primary/alternate for Double Metaphone), and whether they match.',
    `\tsoundex := ${encoderExpr('soundex', o)}`,
    `\tmetaphone := ${encoderExpr('metaphone', o)}`,
    `\tnysiis := ${encoderExpr('nysiis', o)}`,
    `\tdm := ${encoderExpr('doublemetaphone', o)}`,
    '\tpriA, altA := dm.Encode(a)',
    '\tpriB, altB := dm.Encode(b)',
    '\tfmt.Println()',
    code('Soundex', 'soundex'),
    code('Metaphone', 'metaphone'),
    `\tfmt.Printf("%-20s %-10q %-10q %t\\n", "Double Metaphone", priA+"/"+altA, priB+"/"+altB, dm.Match(a, b))`,
    code('NYSIIS', 'nysiis'),
    '}',
  ];
  return file(version, o.ignoreCase ? ['fmt', 'strings'] : ['fmt'], body);
}

export interface SearchSpec {
  query: string;
  candidates: string[];
  metric: MetricId;
  /** FindTopN when > 0, FindAboveThreshold otherwise. */
  topN: number;
  threshold: number;
}

export function searchProgram(s: SearchSpec, o: Options, version: string): string {
  const find = s.topN > 0 ? `strsim.FindTopN(%q, %c, ${s.topN}, m)` : `strsim.FindAboveThreshold(%q, %c, ${s.threshold}, m)`;
  const body = [
    ...adapter(s.metric),
    'func main() {',
    `\tquery := ${str(s.query)}`,
    '\tcandidates := []string{',
    ...s.candidates.map((c) => `\t\t${str(c)},`),
    '\t}',
    '',
    `\tm := ${metricExpr(s.metric, o)} // ${algo(s.metric).name}`,
  ];
  if (o.ignoreCase) {
    body.push(
      '',
      '\t// Compare in lowercase, as in the playground, and print the original spelling.',
      '\tlower := make([]string, len(candidates))',
      '\tfor i, c := range candidates {',
      '\t\tlower[i] = strings.ToLower(c)',
      '\t}',
      `\tfor _, match := range ${find.replace('%q', 'strings.ToLower(query)').replace('%c', 'lower')} {`,
      '\t\tfmt.Printf("%.4f  %s\\n", match.Similarity, candidates[match.Index])',
      '\t}',
    );
  } else {
    body.push(`\tfor _, match := range ${find.replace('%q', 'query').replace('%c', 'candidates')} {`, '\t\tfmt.Printf("%.4f  %s\\n", match.Similarity, match.Value)', '\t}');
  }
  body.push('}');
  return file(version, o.ignoreCase ? ['fmt', 'strings'] : ['fmt'], body);
}

export interface CalibrateSpec {
  algo: AlgoId;
  /** Ignored for phonetic encoders, which match or not. */
  threshold: number;
  pairs: { a: string; b: string; same: boolean }[];
}

export function calibrateProgram(s: CalibrateSpec, o: Options, version: string): string {
  const name = algo(s.algo).name;
  let decl: string;
  let test: string;
  let doc: string;
  if (isEncoder(s.algo)) {
    decl = `var encoder = ${encoderExpr(s.algo, o)}`;
    test = '\treturn encoder.Match(a, b)';
    doc = `// same reports whether a and b are the same name: their ${name} codes match.`;
  } else if (Number.isFinite(s.threshold)) {
    decl = `var metric = ${metricExpr(s.algo, o)}`;
    test = `\treturn metric.Similarity(a, b) >= ${s.threshold}`;
    doc = `// same reports whether a and b are the same: ${name} similarity of ${s.threshold} or more.`;
  } else {
    decl = `var metric = ${metricExpr(s.algo, o)}`;
    test = `\treturn metric.Similarity(a, b) > 1 // no threshold kept a labeled pair`;
    doc = `// same never accepts a pair: on the labeled pairs, keeping none scored best.`;
  }
  const body = [
    ...(isEncoder(s.algo) ? [] : adapter(s.algo)),
    decl,
    '',
    doc,
    'func same(a, b string) bool {',
    ...(o.ignoreCase ? ['\ta, b = strings.ToLower(a), strings.ToLower(b)'] : []),
    test,
    '}',
    '',
    'func main() {',
    '\tpairs := []struct {',
    '\t\ta, b string',
    '\t\tsame bool',
    '\t}{',
    ...s.pairs.map((p) => `\t\t{${str(p.a)}, ${str(p.b)}, ${p.same}},`),
    '\t}',
    '',
    '\tright := 0',
    '\tfor _, p := range pairs {',
    '\t\tif same(p.a, p.b) == p.same {',
    '\t\t\tright++',
    '\t\t} else {',
    '\t\t\tfmt.Printf("wrong: %q and %q\\n", p.a, p.b)',
    '\t\t}',
    '\t}',
    '\tfmt.Printf("%d of %d pairs right\\n", right, len(pairs))',
    '}',
  ];
  return file(version, o.ignoreCase ? ['fmt', 'strings'] : ['fmt'], body);
}
